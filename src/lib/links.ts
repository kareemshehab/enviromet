import type { Media } from '@/payload-types'

export type LinkData = {
  type?: 'reference' | 'custom' | null
  label?: string | null
  url?: string | null
  newTab?: boolean | null
  appearance?: 'button' | 'secondary' | 'white' | 'text' | 'plain' | null
  reference?: {
    relationTo: 'pages' | 'services'
    value: number | string | { slug?: string | null }
  } | null
}

export const resolveHref = (link?: LinkData | null): string | null => {
  if (!link) return null
  if (link.type === 'reference' && link.reference && typeof link.reference.value === 'object') {
    const slug = link.reference.value.slug
    return !slug || slug === 'home' ? '/' : `/${slug}`
  }
  return link.url || null
}

export const appearanceClass = (appearance?: LinkData['appearance']) =>
  ({
    button: 'button',
    secondary: 'button secondary',
    white: 'button white',
    text: 'text-link',
    plain: undefined,
  })[appearance ?? 'plain']

/* ---------- Media helpers ---------- */

export const asMedia = (m: unknown): Media | null => (m && typeof m === 'object' && 'url' in m ? (m as Media) : null)

export const mediaUrl = (m: unknown): string | undefined => asMedia(m)?.url ?? undefined

/** Builds a srcset from the WebP renditions generated by Payload (see collections/Media.ts). */
export const mediaSrcSet = (m: unknown): string | undefined => {
  const media = asMedia(m)
  if (!media?.sizes) return undefined
  const entries = Object.values(media.sizes)
    .filter((s): s is { url: string; width: number } => Boolean(s?.url && s?.width))
    .sort((a, b) => a.width - b.width)
    .map((s) => `${s.url} ${s.width}w`)
  if (media.width && media.url && !media.mimeType?.includes('png')) entries.push(`${media.url} ${media.width}w`)
  return entries.length ? entries.join(', ') : undefined
}

/* ---------- Block data helpers ---------- */

/** Link fields come typed from payload-types; the renderers only need the LinkData shape. */
export const asLink = (l?: unknown) => (l ?? null) as LinkData | null
export const asLinks = (l?: unknown) => (l ?? []) as LinkData[]

/** 0 → "01" (numbered cards and steps). */
export const pad = (i: number) => String(i + 1).padStart(2, '0')
